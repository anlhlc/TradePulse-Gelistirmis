// Dil yönetim sistemi - window.i18n kullanarak global erişim sağla
window.i18n = {
    currentLang: localStorage.getItem('preferredLanguage') || 'tr',
    
    // Mevcut dili değiştir
    setLanguage: function(lang) {
        if (['tr', 'en'].includes(lang)) {
            this.currentLang = lang;
            localStorage.setItem('preferredLanguage', lang);
            this.updatePageContent();
            console.log('Language changed to:', lang);
        }
    },
    
    // Sayfa içeriğini güncelle
    updatePageContent: function() {
        const lang = this.currentLang;
        const translations = Translations[lang];
        console.log('Updating page content to:', lang);
        
        // data-i18n özniteliğine sahip tüm öğeleri bul ve güncelle
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[key]) {
                element.textContent = translations[key];
            }
        });
        
        // data-i18n-placeholder özniteliğine sahip öğeler için
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            if (translations[key]) {
                element.placeholder = translations[key];
            }
        });
        
        // data-i18n-title özniteliğine sahip öğeler için
        document.querySelectorAll('[data-i18n-title]').forEach(element => {
            const key = element.getAttribute('data-i18n-title');
            if (translations[key]) {
                element.title = translations[key];
            }
        });
        
        // Document title'ı güncelle
        if (translations['doc_title']) {
            document.title = translations['doc_title'];
        }
    },
    
    // Çeviri metni getir
    t: function(key) {
        const translations = Translations[this.currentLang];
        return translations[key] || key;
    }
};

